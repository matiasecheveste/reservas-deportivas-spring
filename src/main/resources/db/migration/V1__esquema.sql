CREATE TABLE canchas (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      varchar(80)    NOT NULL UNIQUE,
  deporte     varchar(20)    NOT NULL CHECK (deporte IN ('FUTBOL_5', 'PADEL', 'TENIS')),
  precio_hora numeric(10, 2) NOT NULL CHECK (precio_hora > 0),
  techada     boolean        NOT NULL DEFAULT false
);

CREATE TABLE reservas (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cancha_id bigint         NOT NULL REFERENCES canchas (id),
  titular   varchar(80)    NOT NULL,
  telefono  varchar(9)     NOT NULL,
  inicio    timestamp      NOT NULL,
  fin       timestamp      NOT NULL,
  importe   numeric(10, 2) NOT NULL,
  estado    varchar(12)    NOT NULL DEFAULT 'CONFIRMADA' CHECK (estado IN ('CONFIRMADA', 'CANCELADA')),
  version   bigint         NOT NULL DEFAULT 0,
  CHECK (fin > inicio)
);

CREATE INDEX reservas_cancha_inicio_idx ON reservas (cancha_id, inicio);
